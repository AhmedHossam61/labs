#!/usr/bin/env python3
"""
CSE 532 - Lab 2, Question 3: Hybrid Encryption Architecture (Educational Demo)
=============================================================================

PURPOSE AND SCOPE
-----------------
Question 3 of the lab describes the internal architecture of file-encrypting
ransomware. The *mechanism* it relies on - "hybrid encryption" - is a standard,
legitimate cryptographic construction used every day by TLS, PGP/GPG, S/MIME,
age, and disk-encryption tools. This script studies and demonstrates THAT
mechanism in a safe, defensible way, so the architecture can be understood and
defended against.

This program is DELIBERATELY NON-DESTRUCTIVE. It is a teaching model, not a
weapon. Specifically, it:

  * operates ONLY inside a self-created sandbox directory;
  * generates its OWN synthetic sample files (no real user data is read);
  * writes ciphertext to NEW files and KEEPS every original intact
    (nothing is overwritten in place, nothing is renamed destructively,
    nothing is deleted);
  * does NOT scan the current working directory or any real location;
  * decrypts everything back and verifies a perfect round-trip.

It therefore demonstrates exactly how key-encapsulation (RSA) + bulk symmetric
encryption (AES-GCM) fit together, which is what a defender must understand to
recognise, prevent, and recover from this class of malware - without producing
anything that could cause harm.

THE HYBRID ENCRYPTION ARCHITECTURE
----------------------------------
Public-key crypto (RSA) is slow and size-limited; symmetric crypto (AES) is
fast and handles bulk data. Hybrid encryption combines their strengths:

  1. Generate a fresh random symmetric "session key" k (here: AES-256).
  2. Encrypt the bulk data with k using an authenticated cipher (AES-GCM).
  3. Encrypt (encapsulate) k itself under the recipient's RSA public key
     (RSA-OAEP). Only the holder of the RSA private key can recover k.

Recovery requires BOTH the wrapped key and the private key. In this demo the
private key is produced locally and used immediately to prove reversibility -
the defender's perspective (backup/escrow/recovery), not an attacker's.

Usage
-----
    python -I q3_hybrid_encryption_demo.py [sandbox_dir]

Defaults to a 'q3_sandbox' folder next to this script. The sandbox is created
fresh; if it already exists the script stops rather than disturb its contents.
"""
from __future__ import annotations

import sys
from pathlib import Path

from Crypto.Cipher import AES, PKCS1_OAEP
from Crypto.Hash import SHA256
from Crypto.PublicKey import RSA
from Crypto.Random import get_random_bytes

RSA_BITS = 2048          # key-encapsulation key size
AES_KEY_BYTES = 32       # AES-256 session key
SAMPLE_FILES = {
    "notes.txt": b"Synthetic study note generated by the demo. No real data.\n" * 8,
    "budget.txt": b"item,amount\ncoffee,3\nbooks,40\n(synthetic sample)\n" * 5,
    "readme.txt": b"This file was created by the hybrid-encryption demo itself.\n" * 6,
}


def banner(title: str) -> None:
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def generate_keypair(sandbox: Path) -> RSA.RsaKey:
    """Step 1 - key generation (analogous to KG.py, but kept in the sandbox)."""
    banner("STEP 1  Key generation (RSA key-encapsulation keypair)")
    key = RSA.generate(RSA_BITS)
    (sandbox / "demo_public.pem").write_bytes(key.publickey().export_key())
    # The private key is written to the sandbox only so the demo can show the
    # recovery/decryption half. It is clearly labelled and never leaves here.
    (sandbox / "demo_private.pem").write_bytes(key.export_key())
    print(f"Generated RSA-{RSA_BITS} keypair.")
    print("  public  -> demo_public.pem   (would be the 'enc' / embedded key)")
    print("  private -> demo_private.pem  (the recovery key; kept local only)")
    return key


def create_synthetic_data(sandbox: Path) -> None:
    """Create our OWN sample .txt files. No real files are ever touched."""
    banner("STEP 2  Create synthetic sample files (no real data involved)")
    data_dir = sandbox / "data"
    data_dir.mkdir(exist_ok=True)
    for name, content in SAMPLE_FILES.items():
        (data_dir / name).write_bytes(content)
        print(f"  created data/{name:<12} ({len(content)} bytes)")


def wrap_session_key(public_key: RSA.RsaKey, sandbox: Path) -> bytes:
    """Steps 2b/2c - make a session key and encapsulate it under RSA-OAEP."""
    banner("STEP 3  Session key + key encapsulation (the hybrid core)")
    session_key = get_random_bytes(AES_KEY_BYTES)
    wrapped = PKCS1_OAEP.new(public_key).encrypt(session_key)
    (sandbox / "EncryptedSessionKey.bin").write_bytes(wrapped)
    print(f"Random AES-256 session key generated ({AES_KEY_BYTES} bytes).")
    print(f"Encapsulated under RSA-OAEP -> EncryptedSessionKey.bin "
          f"({len(wrapped)} bytes).")
    print("The plaintext session key is NOT written to disk anywhere.")
    return session_key


def encrypt_non_destructively(session_key: bytes, sandbox: Path) -> None:
    """
    Encrypt the synthetic files with AES-256-GCM.

    NON-DESTRUCTIVE: ciphertext goes to a SEPARATE 'encrypted' directory as new
    '<name>.enc' files. Every original in 'data/' is left byte-for-byte intact.
    This is the deliberate, ethical departure from the destructive behaviour
    described in the assignment.
    """
    banner("STEP 4  Bulk encryption with AES-256-GCM (originals preserved)")
    data_dir = sandbox / "data"
    enc_dir = sandbox / "encrypted"
    enc_dir.mkdir(exist_ok=True)

    for src in sorted(data_dir.glob("*.txt")):
        plaintext = src.read_bytes()
        nonce = get_random_bytes(12)
        cipher = AES.new(session_key, AES.MODE_GCM, nonce=nonce)
        ciphertext, tag = cipher.encrypt_and_digest(plaintext)
        # Self-describing container: nonce | tag | ciphertext.
        out = enc_dir / (src.name + ".enc")
        out.write_bytes(nonce + tag + ciphertext)
        assert src.exists(), "original must still be present"
        print(f"  data/{src.name:<12} -> encrypted/{out.name:<18} "
              f"(original kept: {src.exists()})")


def decrypt_and_verify(private_key: RSA.RsaKey, sandbox: Path) -> bool:
    """
    Recovery half - recover the session key from the wrapped blob with the
    private key, decrypt the ciphertext, and verify it matches the originals.
    Output goes to a 'recovered' directory; nothing is overwritten.
    """
    banner("STEP 5  Recovery: unwrap key, decrypt, verify round-trip")
    wrapped = (sandbox / "EncryptedSessionKey.bin").read_bytes()
    session_key = PKCS1_OAEP.new(private_key).decrypt(wrapped)
    print("Recovered the AES session key via the RSA private key.")

    data_dir = sandbox / "data"
    enc_dir = sandbox / "encrypted"
    rec_dir = sandbox / "recovered"
    rec_dir.mkdir(exist_ok=True)

    all_ok = True
    for enc in sorted(enc_dir.glob("*.enc")):
        blob = enc.read_bytes()
        nonce, tag, ciphertext = blob[:12], blob[12:28], blob[28:]
        cipher = AES.new(session_key, AES.MODE_GCM, nonce=nonce)
        try:
            plaintext = cipher.decrypt_and_verify(ciphertext, tag)  # auth check
        except ValueError:
            print(f"  {enc.name}: AUTHENTICATION FAILED (tampered?)")
            all_ok = False
            continue
        original_name = enc.name[:-4]  # strip ".enc"
        (rec_dir / original_name).write_bytes(plaintext)
        original = (data_dir / original_name).read_bytes()
        match = plaintext == original
        all_ok &= match
        print(f"  {enc.name:<18} -> recovered/{original_name:<12} "
              f"match={match}")
    return all_ok


def integrity_summary(sandbox: Path) -> None:
    banner("SUMMARY  Non-destructive guarantee")
    data_dir = sandbox / "data"
    for src in sorted(data_dir.glob("*.txt")):
        digest = SHA256.new(src.read_bytes()).hexdigest()[:16]
        print(f"  original data/{src.name:<12} still present, sha256={digest}...")
    print("\nNo original file was overwritten, renamed, or deleted.")
    print("Ciphertext and recovered copies live in separate sandbox folders.")


def main() -> int:
    script_dir = Path(__file__).resolve().parent
    sandbox = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else script_dir / "q3_sandbox"

    if sandbox.exists():
        print(f"[STOP] Sandbox '{sandbox}' already exists. "
              f"Remove it or pass a fresh path, so nothing is disturbed.",
              file=sys.stderr)
        return 2
    sandbox.mkdir(parents=True)
    print(f"Sandbox created at: {sandbox}")
    print("This demo stays entirely within that folder.")

    key = generate_keypair(sandbox)
    create_synthetic_data(sandbox)
    session_key = wrap_session_key(key.publickey(), sandbox)
    encrypt_non_destructively(session_key, sandbox)
    ok = decrypt_and_verify(key, sandbox)
    integrity_summary(sandbox)

    banner("RESULT")
    print("Hybrid encryption round-trip succeeded." if ok else "Round-trip FAILED.")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
